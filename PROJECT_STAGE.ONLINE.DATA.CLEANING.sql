---USE OF RIGHT (KEEPS THE TEXT FROM THE RIGHT SIDE, AFTER THE COMMA)
---USE OF RTRIM AND LTRIM SO WE CAN REMOVE SPACES BEFORE AND AFTER THE VALUES.

