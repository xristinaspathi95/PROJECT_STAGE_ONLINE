---NEXT STEP: WE WANT TO TRANSFER THE CLEAN DATA INTO A NEW TABLE
---STEP 1: WE CREATE A STORE PROCEDURE WITH THE PURPOSE TO DOWNLOAD AND CLEAN AUTOMATICALLY NEW RAW DATA.

CREATE PROCEDURE CUSTOMER_CLEAN
AS BEGIN
 TRUNCATE TABLE FACT_ONLINESALES        ---EMPTIES THE TABLE FOR AVOIDING THE DUPLICATES
 INSERT INTO FACT_ONLINESALES 
   (INVOICENO, STOCKCODE, DESCRIPTION, QUANTITY,INVOICEDATE,UNITPRICE, CUSTOMERID, COUNTRY)
   SELECT
   INVOICENO, STOCKCODE, DESCRIPTION,    ---TEXT COLUMNS: KEPT AS NVARCHAR
   TRY_CONVERT(INT, QUANTITY),           ---CONVERT COLUMNS TO THE APPROPRIATE DATA TYPES
   TRY_CONVERT(DATETIME, INVOICEDATE),   ---INVALID VALUES WILL BECOME NULL
   TRY_CONVERT(DECIMAL(18,2),UNITPRICE),
   TRY_CONVERT(INT,
   CASE 
     WHEN CUSTOMERID=' ' THEN -1         ---MISSING OR INVALID CUSTOMERID WILL APPEAR AS -1
     WHEN CUSTOMERID LIKE '%.%' THEN -1  
     WHEN CUSTOMERID LIKE '%/%' THEN -1  ---MISSING COUNTRIES WILL APPEAR AS NO COUNTRY
     ELSE CUSTOMERID
   END),
   CASE
     WHEN COUNTRY=' ' THEN 'NO COUNTRY'
     ELSE COUNTRY
   END
FROM STG_ONLINERETAIL
END
GO

---RUN THE PROCEDURE
EXEC CUSTOMER_CLEAN

